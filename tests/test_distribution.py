def test_d20():
    dist = distribution("1d20")
    assert dist.min() == 1
    assert dist.max() == 20
    assert len(list(dist.keys())) == 20

    for d in range(dist.min(), dist.max() + 1):
        assert dist.get(d) == 1 / 20


def test_exceptions():
    with pytest.raises(ZeroDivisionError):
        distribution("1d6 / 0")

    with pytest.raises(RollSyntaxError):
        distribution("1d20 +")


